/**
 * Utility script to sync variables from .env to env.js for the Chrome Extension.
 * Usage: node sync_env.js
 */
const fs = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '.env');
const envJsPath = path.join(__dirname, 'env.js');

if (!fs.existsSync(envPath)) {
  console.log('.env file not found. Creating default .env from .env.example or template...');
  const examplePath = path.join(__dirname, '.env.example');
  if (fs.existsSync(examplePath)) {
    fs.copyFileSync(examplePath, envPath);
  }
}

const envVars = {
  AI_PROVIDER: 'gemini',
  GEMINI_API_KEY: '',
  DEFAULT_MODEL: 'gemini-3.5-flash-lite',
  GROQ_API_KEY: '',
  GROQ_MODEL: 'openai/gpt-oss-120b'
};

if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, 'utf8');
  content.split(/\r?\n/).forEach(line => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const match = trimmed.match(/^([^=]+)=(.*)$/);
    if (match) {
      const key = match[1].trim();
      let value = match[2].trim();
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1);
      }
      envVars[key] = value;
    }
  });
}

const envJsContent = `// Auto-generated by sync_env.js from .env
// DO NOT commit this file to public git repositories if it contains sensitive keys.
(function (root) {
  const ENV = ${JSON.stringify(envVars, null, 2)};

  if (typeof module !== "undefined" && module.exports) {
    module.exports = ENV;
  }
  if (typeof globalThis !== "undefined") {
    globalThis.ENV = ENV;
  }
  if (typeof self !== "undefined") {
    self.ENV = ENV;
  }
  if (typeof window !== "undefined") {
    window.ENV = ENV;
  }
})(typeof globalThis !== "undefined" ? globalThis : this);
`;

fs.writeFileSync(envJsPath, envJsContent, 'utf8');
console.log('Successfully synced .env -> env.js');
console.log('Variables loaded:', Object.keys(envVars).join(', '));
